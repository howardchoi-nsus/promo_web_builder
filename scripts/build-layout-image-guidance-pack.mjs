import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const packRoot = new URL('docs/mouse-swarm-builder/layout-image-phase1/', root);
const manifest = JSON.parse(readFileSync(new URL('manifest.json', packRoot), 'utf8'));
const prior = readFileSync(new URL('docs/mouse-swarm-builder/layout-diversity-prompt-pack/apply-two-prompt-bodies.sql', root), 'utf8');
const legacyPatches = new Map([...prior.matchAll(/\('([^']+)', \$layout_patch\$([\s\S]*?)\$layout_patch\$\)/g)].map(match => [match[1], match[2]]));
if (legacyPatches.size !== 2) throw Error('Expected the reviewed two-prompt data update');
const literal = value => "'" + value.replaceAll("'", "''") + "'";
const entries = manifest.prompts.map(entry => {
  const full = readFileSync(new URL(entry.file, packRoot), 'utf8');
  const start = full.indexOf(entry.guidanceHeading);
  if (start < 0) throw Error('Missing guidance block for ' + entry.type);
  const recognition = full.slice(start).trim();
  const patch = legacyPatches.get(entry.type) || recognition;
  return { ...entry, patch, recognition, marker: legacyPatches.has(entry.type)
    ? '<!-- layout-diversity-prompt-only-v1 -->' : '<!-- layout-image-phase1-v1 -->' };
});
function replaceOnce(text, before, after) {
  if (text.split(before).length !== 2) throw Error('Reviewed SQL template changed: ' + before);
  return text.replace(before, after);
}
const start = prior.indexOf('  for item in select * from (values');
const end = prior.indexOf('  ) as patches(prompt_type, patch_body)');
if (start < 0 || end < start) throw Error('Reviewed SQL boundaries changed');
const tuples = entries.map(entry => `(${literal(entry.type)}, ${literal(entry.marker)}, ${literal(entry.patch)}, ${literal(entry.recognition)})`).join(',\n');
let sql = prior.slice(0, start) + '  for item in select * from (values\n' + tuples + '\n' + prior.slice(end);
sql = replaceOnce(sql, "note constant text := 'Layout diversity prompt-only v1: preserve current config; Admin validation required';", "note constant text := 'Migration 102: layout and GGPoker written image guidance; Admin validation required';");
sql = replaceOnce(sql, "marker constant text := '<!-- layout-diversity-prompt-only-v1 -->';", 'marker text;');
sql = replaceOnce(sql, 'as patches(prompt_type, patch_body)', 'as patches(prompt_type, patch_marker, patch_body, recognition_body)');
sql = replaceOnce(sql, '  loop\n', '  loop\n    marker := item.patch_marker;\n');
for (const row of ['active_row', 'target_row']) {
  sql = replaceOnce(sql, `position(item.patch_body in ${row}.body)>0`, `position(item.recognition_body in ${row}.body)>0`);
}
for (const row of ['active_row', 'target_row']) {
  sql = replaceOnce(sql, `if ${row}.model_options->>'pageDraftContractVersion' is distinct from '2' then`,
    `if item.prompt_type in ('promo_page_manifest_planner','promo_page_region_builder')\n      and ${row}.model_options->>'pageDraftContractVersion' is distinct from '2' then`);
}
const allTypes = entries.map(entry => literal(entry.type)).join(',');
sql = replaceOnce(sql, "where type in ('promo_page_manifest_planner','promo_page_region_builder')", `where type in (${allTypes})`);
sql = replaceOnce(sql, "and position('<!-- layout-diversity-prompt-only-v1 -->' in body)>0", "and (position('<!-- layout-diversity-prompt-only-v1 -->' in body)>0\n    or position('<!-- layout-image-phase1-v1 -->' in body)>0\n    or position('# CONTENT-LED COMPOSITION DECISIONS' in body)>0\n    or position('# EXPLICIT GEOMETRY WITHIN THE LOCKED SHELL' in body)>0)");
sql = '-- Generated by scripts/build-layout-image-guidance-pack.mjs.\n-- Draft-only DATA update; no schema or active prompt/model/skill changes.\n' + sql;
const output = new URL(manifest.migration, root);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== sql) throw Error('Migration 102 differs from the reviewed prompt sources; regenerate it before applying.');
  console.log('Migration 102 matches the reviewed manifest and prompt sources.');
} else {
  writeFileSync(output, sql);
  console.log('Wrote Draft-only migration 102 for five prompt bodies; existing layout guidance is not duplicated.');
}
