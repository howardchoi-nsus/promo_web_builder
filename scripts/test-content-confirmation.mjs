import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {pendingContentConfirmations,pendingCriticalInputs,assertContentConfirmed,prepareOverviewForPreview} from '../shared/page-schema/content-confirmation.mjs';
import {context} from './fixtures/page-schema.mjs';
const require=createRequire(import.meta.url),server=require('../shared/page-schema/content-confirmation.cjs');
const overview={title:'',mainOffer:'',_review:{missingCriticalInputs:['title','mainOffer']},contentSections:[{title:'참여 안내',description:'미정',confirmationRequired:true,cta:{label:'지금 참여하기',url:'',confirmationRequired:true},items:[{title:'혜택 알아보기',description:'내용을 살펴보세요.',confirmationRequired:true}]}],additionalInformation:[{label:'기간',value:'미정',confirmationRequired:true}],legalInformation:[{title:'약관',body:'',confirmationRequired:true}],notices:[{title:'안내',body:'제공된 안내입니다.',confirmationRequired:true}]};
const before=structuredClone(overview),prepared=prepareOverviewForPreview(overview);
assert.deepEqual(overview,before);
assert.deepEqual(prepared,server.prepareOverviewForPreview(overview));
assert.equal(prepared.omittedItems.length,3);
assert.equal(prepared.overview.contentSections[0].cta,undefined);
assert.equal(prepared.overview.contentSections[0].description,'');
assert.equal(prepared.overview.contentSections[0].items[0].description,'내용을 살펴보세요.');
assert.deepEqual(prepared.overview.legalInformation,[]);
assert.equal(prepared.overview.notices[0].body,'제공된 안내입니다.');
assert.equal(pendingContentConfirmations(prepared.overview).length,0);
assert.ok(pendingCriticalInputs(prepared.overview).every(item=>!item.blocking));
assert.doesNotThrow(()=>assertContentConfirmed(overview));
const {contentContext}=require('../api/_page-schema-service');
const generated=contentContext(overview,context);
assert.ok(Object.values(generated.contentSources).some(source=>source.text==='내용을 살펴보세요.'));
assert.ok(Object.values(generated.contentSources).every(source=>source.text!=='미정'));
assert.deepEqual(generated.actions,{});
console.log('Content review is advisory: missing editorial inputs allowed, unknown facts omitted, known copy preserved, immutable client/server parity passed.');
