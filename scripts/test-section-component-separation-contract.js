const assert = require("node:assert");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), "utf8");
const migration = read("db", "migrations", "029_item_components_design_tokens_and_planner.sql");
const itemStore = read("api", "_item-components-store.js");
const itemApi = read("api", "item-components.js");
const sectionItemApi = read("api", "wizard-content-section-items.js");
const sectionStore = read("api", "_wizard-content-sections-store.js");
const templateApi = read("api", "wizard-form-template-sections.js");
const templateStore = read("api", "_wizard-form-templates-store.js");
const publicApi = read("api", "wizard-form-template-public.js");
const adminHtml = read("prototype", "index.html");
const adminApp = read("prototype", "app.js");
const seed = read("db", "seeds", "004_seed_item_components_design_tokens_and_default_template.sql");

assert.match(migration, /create table if not exists wizard_item_components/);
assert.match(migration, /default \('cmp_' \|\| replace\(gen_random_uuid\(\)::text, '-', ''\)\)/);
assert.match(migration, /create table if not exists wizard_item_component_versions/);
assert.match(migration, /create table if not exists wizard_content_section_component_instances/);
assert.match(migration, /component_version_id uuid not null/);
assert.match(migration, /drop table if exists wizard_section_components/);
assert.match(migration, /alter table wizard_content_sections drop column if exists component_id/);
assert.match(itemApi, /componentKey is generated by the server/);
assert.doesNotMatch(itemApi, /insert into wizard_item_components \(component_key/);
assert.match(itemStore, /FIELD_KINDS = \["text", "image", "cta"\]/);
assert.match(sectionItemApi, /componentVersionId is required/);
assert.match(sectionItemApi, /Component definitions cannot be created from a section/);
assert.doesNotMatch(sectionItemApi, /insert into wizard_content_section_items/);
assert.match(sectionStore, /wizard_content_section_component_instances/);
assert.match(sectionStore, /componentVersionId: row\.component_version_id/);
assert.match(templateApi, /templateId and sectionId are required/);
assert.doesNotMatch(templateStore, /wizard_section_components/);
assert.doesNotMatch(publicApi, /componentId: membership\.componentId/);
assert.match(adminHtml, /adminTab === 'components'/);
assert.match(adminHtml, /wizardItemEditor\.componentVersionId/);
assert.match(adminApp, /newWizardFormTemplateSectionForm: \{ sectionId: "" \}/);
assert.match(seed, /'hero-title', 'Hero Title'/);
assert.match(seed, /'content-image', 'Content Image'/);
assert.doesNotMatch(seed, /insert into wizard_content_section_items/);

console.log("Item component separation contract test passed");
